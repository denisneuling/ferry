package v1

import (
	"os"
	"regexp"
	"testing"

	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
	"github.com/oapi-codegen/oapi-codegen/v2/pkg/util"
	"go.yaml.in/yaml/v4"
)

// TestGeneratedCodeIsCurrent regenerates v1.gen.go from the spec, the way
// `make generate-api` does, and fails if the committed file differs. A spec
// edited without regenerating would otherwise go unnoticed until a handler
// failed to match it at runtime — which generating from the spec is meant to
// rule out.
func TestGeneratedCodeIsCurrent(t *testing.T) {
	raw, err := os.ReadFile("config.yaml")
	if err != nil {
		t.Fatal(err)
	}
	var cfg codegen.Configuration
	if err := yaml.Unmarshal(raw, &cfg); err != nil {
		t.Fatal(err)
	}
	cfg = cfg.UpdateDefaults()
	if err := cfg.Validate(); err != nil {
		t.Fatal(err)
	}
	spec, err := util.LoadSwagger("../openapi/ferry-v1.yaml")
	if err != nil {
		t.Fatal(err)
	}
	want, err := codegen.Generate(spec, cfg)
	if err != nil {
		t.Fatal(err)
	}
	have, err := os.ReadFile("v1.gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if withoutHeader(want) != withoutHeader(string(have)) {
		t.Error("v1.gen.go is out of date with api/openapi/ferry-v1.yaml: run `make generate-api`")
	}
}

// header is the "Code generated by" line. It names the module that ran the
// generator, which is oapi-codegen for `go tool` and this module for the test.
var header = regexp.MustCompile(`(?m)^// Code generated by .* DO NOT EDIT\.$`)

func withoutHeader(code string) string { return header.ReplaceAllString(code, "") }
